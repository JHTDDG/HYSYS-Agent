"""输入文本规范化：把化学式/单位/符号的各种 Unicode 写法统一成解析层友好的 ASCII 形式。

覆盖用户在网页输入框的常见写法：
  - 化学式下标     CH₄、C₇H₈、H₂O            -> CH4、C7H8、H2O
  - 单位上标       Nm³/h、kg/cm²、m³          -> Nm3/h、kg/cm2、m3（仅紧跟字母时转换；
                                                10³ 这类数字上标不动，避免 10^3 变 103）
  - 全角字符       ２５MPa、ＣＨ４、k＝0.01、（液）  -> 半角
  - 平衡/反应箭头  ⇌ ⇋ ↔ ⟺ ⟶ → ⇒            -> =
  - 相态标注       (g) (l) (s) (aq) (气) (液) (固) -> 去除
  - 负号变体       −40（U+2212）、–40、—40    -> -40
  - 不可见空白     不换行空格、全角空格        -> 普通空格

幂等：规范化后的文本再次规范化结果不变。
"""
from __future__ import annotations

import re

# 化学式下标数字：无条件转普通数字
_SUBSCRIPTS = str.maketrans("₀₁₂₃₄₅₆₇₈₉", "0123456789")

# 上标数字（单位）：仅当紧跟在字母后面才转（Nm³ -> Nm3），数字后的上标保留原样
_SUPERSCRIPTS = "⁰¹²³⁴⁵⁶⁷⁸⁹"
_SUPER_MAP = {c: d for c, d in zip(_SUPERSCRIPTS, "0123456789")}

# 全角 -> 半角（含负号变体与不可见空白）
_FULLWIDTH = str.maketrans({
    "０": "0", "１": "1", "２": "2", "３": "3", "４": "4",
    "５": "5", "６": "6", "７": "7", "８": "8", "９": "9",
    "Ａ": "A", "Ｂ": "B", "Ｃ": "C", "Ｄ": "D", "Ｅ": "E", "Ｆ": "F", "Ｇ": "G",
    "Ｈ": "H", "Ｉ": "I", "Ｊ": "J", "Ｋ": "K", "Ｌ": "L", "Ｍ": "M", "Ｎ": "N",
    "Ｏ": "O", "Ｐ": "P", "Ｑ": "Q", "Ｒ": "R", "Ｓ": "S", "Ｔ": "T", "Ｕ": "U",
    "Ｖ": "V", "Ｗ": "W", "Ｘ": "X", "Ｙ": "Y", "Ｚ": "Z",
    "ａ": "a", "ｂ": "b", "ｃ": "c", "ｄ": "d", "ｅ": "e", "ｆ": "f", "ｇ": "g",
    "ｈ": "h", "ｉ": "i", "ｊ": "j", "ｋ": "k", "ｌ": "l", "ｍ": "m", "ｎ": "n",
    "ｏ": "o", "ｐ": "p", "ｑ": "q", "ｒ": "r", "ｓ": "s", "ｔ": "t", "ｕ": "u",
    "ｖ": "v", "ｗ": "w", "ｘ": "x", "ｙ": "y", "ｚ": "z",
    "＝": "=", "＋": "+", "－": "-", "：": ":", "（": "(", "）": ")",
    "．": ".", "／": "/", "％": "%",
    "−": "-",   # U+2212 数学负号
    "–": "-",   # en dash
    "—": "-",   # em dash
    "\u00a0": " ", "\u3000": " ",  # 不换行空格 / 全角空格
})

# 平衡箭头 / 单向箭头 -> 等号（方程解析只认 = / -> / → / =>）
_ARROW_RE = re.compile(r"[⇌⇋⇎⇔⇒⇐⇶⇀↽↔⟺⟷⟶⟹→←]")

# 相态标注：(g) (l) (s) (aq) (gas) (liquid) (气) (液) (气相) ...
# \b 防止误伤 "(LPG)" 这类以 g/l/s 开头的缩写词
_PHASE_RE = re.compile(
    r"[（(]\s*(?:gas|liquid|solid|aq|g|l|s|气相|液相|固相|气|液|固|蒸汽)\s*[)）]", re.I)


def normalize_text(text: str) -> str:
    if not text:
        return text
    text = text.translate(_FULLWIDTH)
    text = text.translate(_SUBSCRIPTS)
    text = re.sub(r"(?<=[A-Za-z])[" + _SUPERSCRIPTS + r"]+",
                  lambda m: "".join(_SUPER_MAP[c] for c in m.group()), text)
    text = _ARROW_RE.sub("=", text)
    text = _PHASE_RE.sub("", text)
    return text
